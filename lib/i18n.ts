const DICTS: Record<Lang, Dict> = { zh, ja, en };

export type Vars = Record<string, string | number>;
export type T = (key: Key, vars?: Vars) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? zh[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const isLang = (v: unknown): v is Lang => typeof v === "string" && (LANGS as readonly string[]).includes(v);

/** Cookie 优先；否则按浏览器 Accept-Language 选；都没有时用中文 */
export function pickLang(cookie: string | undefined, acceptLanguage: string | null | undefined): Lang {
  if (isLang(cookie)) return cookie;
  for (const part of (acceptLanguage ?? "").toLowerCase().split(",")) {
    const code = part.trim().slice(0, 2);
    if (code === "ja") return "ja";
    if (code === "zh") return "zh";
    if (code === "en") return "en";
  }
  return "zh";
}

const LOCALE: Record<Lang, string> = { zh: "zh-CN", ja: "ja-JP", en: "en-US" };

export function formatDateFor(lang: Lang, iso: string) {
  return new Date(iso).toLocaleString(LOCALE[lang], {
    timeZone: "Asia/Tokyo",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });
}

/** 服务端 API 返回的错误：{ error: 词典键, vars } */
export function errorText(t: T, body: { error?: string; vars?: Vars } | null | undefined, fallback: Key = "genericError") {
  const key = body?.error;
  if (key && `err_${key}` in zh) return t(`err_${key}` as Key, body?.vars);
  return t(fallback);
}
